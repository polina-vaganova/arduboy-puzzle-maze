void copyLevel(const byte src[16][12]) {
  for (int x = 0; x < 16; x++) {
    for (int y = 0; y < 12; y++) {
      maze[x][y] = pgm_read_byte(&(src[x][y]));
    }
  }
}

void loadLevel(int level) {
  switch(level) {
    case 1: copyLevel(level1); break;
    case 2: copyLevel(level2); break;
    case 3: copyLevel(level3); break;
    case 4: copyLevel(level4); break;

    default:
      copyLevel(level1);
      break;
  }
}
